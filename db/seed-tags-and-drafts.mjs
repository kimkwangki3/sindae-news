import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "fs";

const env = Object.fromEntries(
  readFileSync(".env.local", "utf8")
    .split("\n")
    .filter((l) => l.includes("=") && !l.trim().startsWith("#"))
    .map((l) => {
      const i = l.indexOf("=");
      return [l.slice(0, i).trim(), l.slice(i + 1).trim()];
    }),
);
const sb = createClient(
  env.NEXT_PUBLIC_SUPABASE_URL,
  env.SUPABASE_SERVICE_ROLE_KEY,
  { auth: { persistSession: false } },
);

// tags 컬럼이 없으면 여기서 멈춘다. 없는 채로 진행하면 update가 조용히
// 실패하거나 알아보기 어려운 오류만 남는다.
{
  const { error } = await sb.from("articles").select("tags").limit(1);
  if (error) {
    console.error("tags 컬럼을 읽지 못했습니다:", error.message);
    console.error(
      "→ Supabase SQL Editor에서 db/article-tags-migration.sql 을 먼저 실행하세요.",
    );
    process.exit(1);
  }
}

